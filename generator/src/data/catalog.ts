function actionSkill(action: string): string {
  const a = action.toLowerCase();
  if (a.includes("демонтаж")) return "Демонтаж";
  if (
    a.includes("диагност") ||
    a.includes("локализац") ||
    a.includes("провер") ||
    a.includes("прозвон") ||
    a.includes("обследова")
  ) {
    return "Диагностика";
  }
  if (
    a.includes("измер") ||
    a.includes("тест") ||
    a.includes("калибр") ||
    a.includes("поверк") ||
    a.includes("юстир")
  ) {
    return "Измерения";
  }
  if (
    a.includes("настрой") ||
    a.includes("программ") ||
    a.includes("адресац") ||
    a.includes("обновлен") ||
    a.includes("прошив") ||
    a.includes("резерв")
  ) {
    return "Пусконаладка";
  }
  if (
    a.includes("оформл") ||
    a.includes("паспорт") ||
    a.includes("фото") ||
    a.includes("сдач") ||
    a.includes("маркиров") ||
    a.includes("протокол")
  ) {
    return "Документирование";
  }
  if (a.includes("восстанов") || a.includes("временн") || a.includes("переключ") || a.includes("аварийн")) {
    return "Аварийные работы";
  }
  return "Монтаж";
}

function objectExtras(object: string): string[] {
  const o = object.toLowerCase();
  const extra: string[] = [];
  if (o.includes("колод")) extra.push("Работа в колодце");
  if (
    o.includes("мачт") ||
    o.includes("кровл") ||
    o.includes("антенн") ||
    o.includes("фасад") ||
    o.includes("уличн")
  ) {
    extra.push("Работа на высоте");
  }
  if (o.includes("щит") || o.includes("вру") || o.includes("ибп") || o.includes("питани")) {
    extra.push("Электробезопасность");
  }
  if (o.includes("заказчик") || o.includes("акт ")) extra.push("Согласование с заказчиком");
  return extra;
}

function skillSet(names: string[]): string[] {
  return [...new Set(names.filter(Boolean))].slice(0, 3);
}

export function buildCatalog(): { skills: CatalogSkill[]; tasks: CatalogTask[] } {
  const skillIndex = new Map<string, CatalogSkill>();
  let skillN = 0;
  const addSkill = (name: string, domain: string) => {
    if (skillIndex.has(name)) return;
    skillN += 1;
    skillIndex.set(name, {
      id: `S${String(skillN).padStart(4, "0")}`,
      name,
      domain,
    });
  };

  for (const name of SHARED) addSkill(name, "Общие");
  for (const spec of DOMAINS) addSkill(spec.skill, spec.name);

  const tasks: CatalogTask[] = [];
  let taskN = 0;
  const usedTitles = new Set<string>();
  const pushTask = (title: string, skills: string[], domain: string) => {
    const unique = skillSet(skills);
    if (unique.length === 0) return;
    if (usedTitles.has(title)) return;
    usedTitles.add(title);
    for (const s of unique) {
      if (!skillIndex.has(s)) addSkill(s, domain);
    }
    taskN += 1;
    const n = unique.length as 1 | 2 | 3;
    const durationMin: [number, number] =
      n === 1 ? [20, 45] : n === 2 ? [40, 80] : [70, 120];
    tasks.push({
      id: `T${String(taskN).padStart(4, "0")}`,
      title,
      skills: unique,
      domain,
      durationMin,
    });
  };

  for (const spec of DOMAINS) {
    for (const [title, skills] of spec.jobs) {
      pushTask(title, skills, spec.name);
    }
    let i = 0;
    for (const object of spec.objects) {
      for (const action of spec.actions) {
        const extras = [actionSkill(action), ...objectExtras(object)].filter((s) => s !== spec.skill);
        const n = (1 + (i % 3)) as 1 | 2 | 3;
        i += 1;
        const pad = ["Документирование", "Согласование с заказчиком", "Диагностика"];
        const pool = [spec.skill, ...extras, ...pad];
        pushTask(`${action}: ${object}`, pool.slice(0, n), spec.name);
      }
    }
  }

  return { skills: [...skillIndex.values()], tasks };
}

export const CATALOG = buildCatalog();
